"""Write tools/sipp/uac_intake.xml.

    python tools/sipp/make_scenario.py

The scenario places one inbound call (G.711 offer plus telephone-event), plays the recorded caller side from media/call.pcap, and then
waits for the line's BYE. While it waits it sends an in-dialog OPTIONS every 15 seconds: Docker Desktop forwards UDP through a NAT that
forgets an idle mapping, so a BYE sent by the line after a long quiet stretch would never reach the container. The keepalives are
unrolled (one block each, with their own CSeq) because SIPp prints a numeric variable as 2.000000, which is not a CSeq.
If no BYE has come after the last keepalive, SIPp hangs up itself.
"""
from pathlib import Path

KEEPALIVES = 11
HEAD = """<?xml version="1.0" encoding="ISO-8859-1" ?>
<!DOCTYPE scenario SYSTEM "sipp.dtd">

<!-- Generated by make_scenario.py: an inbound call to the intake line from SIPp. INVITE with a G.711 offer (PCMA first), then the
     recorded caller side of a reference call from media/call.pcap (speech as PCMU, keypad digits as RFC 4733 events), then the
     line's BYE is answered. In-dialog OPTIONS every 15 seconds keep Docker Desktop's UDP mapping alive. -->
<scenario name="sipclerk inbound intake">

  <send retrans="500">
    <![CDATA[
      INVITE sip:[service]@[remote_ip]:[remote_port] SIP/2.0
      Via: SIP/2.0/[transport] [local_ip]:[local_port];branch=[branch]
      From: sipp <sip:+17865550131@[local_ip]:[local_port]>;tag=[pid]SIPpTag00[call_number]
      To: <sip:[service]@[remote_ip]:[remote_port]>
      Call-ID: [call_id]
      CSeq: 1 INVITE
      Contact: sip:sipp@[local_ip]:[local_port]
      Max-Forwards: 70
      Subject: sipclerk lab call from SIPp
      Content-Type: application/sdp
      Content-Length: [len]

      v=0
      o=sipp 53655765 2353687637 IN IP[local_ip_type] [local_ip]
      s=-
      c=IN IP[media_ip_type] [media_ip]
      t=0 0
      m=audio [auto_media_port] RTP/AVP 8 0 101
      a=rtpmap:8 PCMA/8000
      a=rtpmap:0 PCMU/8000
      a=rtpmap:101 telephone-event/8000
      a=fmtp:101 0-16
      a=ptime:20
    ]]>
  </send>

  <recv response="100" optional="true"></recv>
  <recv response="180" optional="true"></recv>
  <recv response="200" rtd="true"></recv>

  <send>
    <![CDATA[
      ACK sip:[service]@[remote_ip]:[remote_port] SIP/2.0
      Via: SIP/2.0/[transport] [local_ip]:[local_port];branch=[branch]
      From: sipp <sip:+17865550131@[local_ip]:[local_port]>;tag=[pid]SIPpTag00[call_number]
      To: <sip:[service]@[remote_ip]:[remote_port]>[peer_tag_param]
      Call-ID: [call_id]
      CSeq: 1 ACK
      Max-Forwards: 70
      Content-Length: 0
    ]]>
  </send>

  <nop>
    <action>
      <exec play_pcap_audio="/work/media/call.pcap"/>
    </action>
  </nop>
"""

OK = """  <send>
    <![CDATA[
      SIP/2.0 200 OK
      [last_Via:]
      [last_From:]
      [last_To:]
      [last_Call-ID:]
      [last_CSeq:]
      Contact: <sip:sipp@[local_ip]:[local_port]>
      Content-Length: 0
    ]]>
  </send>
  <nop next="done"></nop>
"""

OPTIONS = """  <label id="ka{i}"/>
  <send retrans="500">
    <![CDATA[
      OPTIONS sip:[service]@[remote_ip]:[remote_port] SIP/2.0
      Via: SIP/2.0/[transport] [local_ip]:[local_port];branch=[branch]
      From: sipp <sip:+17865550131@[local_ip]:[local_port]>;tag=[pid]SIPpTag00[call_number]
      To: <sip:[service]@[remote_ip]:[remote_port]>[peer_tag_param]
      Call-ID: [call_id]
      CSeq: {cseq} OPTIONS
      Max-Forwards: 70
      Content-Length: 0
    ]]>
  </send>
  <recv response="200"></recv>
"""

TAIL = """  <label id="hangup"/>
  <send retrans="500">
    <![CDATA[
      BYE sip:[service]@[remote_ip]:[remote_port] SIP/2.0
      Via: SIP/2.0/[transport] [local_ip]:[local_port];branch=[branch]
      From: sipp <sip:+17865550131@[local_ip]:[local_port]>;tag=[pid]SIPpTag00[call_number]
      To: <sip:[service]@[remote_ip]:[remote_port]>[peer_tag_param]
      Call-ID: [call_id]
      CSeq: {cseq} BYE
      Max-Forwards: 70
      Content-Length: 0
    ]]>
  </send>
  <recv response="200" crlf="true"></recv>

  <label id="done"/>
</scenario>
"""


def build() -> str:
    parts = [HEAD]
    for i in range(KEEPALIVES):
        nxt = f"ka{i}"
        parts.append(f'  <recv request="BYE" timeout="15000" ontimeout="{nxt}"></recv>\n')
        parts.append(OK)
        parts.append(OPTIONS.format(i=i, cseq=i + 2))
    parts.append(f'  <recv request="BYE" timeout="15000" ontimeout="hangup"></recv>\n')
    parts.append(OK)
    parts.append(TAIL.format(cseq=KEEPALIVES + 2))
    return "".join(parts)


if __name__ == "__main__":
    out = Path(__file__).with_name("uac_intake.xml")
    out.write_text(build(), encoding="iso-8859-1", newline="\n")
    print("wrote", out)
